export const questions = attestly.table(
  "questions",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    questionnaireId: uuid("questionnaire_id")
      .notNull()
      .references(() => questionnaires.id, { onDelete: "cascade" }),
    orgId: uuid("org_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    /** 1-based worksheet row; the answer is written back to (row_number, questionnaires.answer_col). */
    rowNumber: integer("row_number").notNull(),
    section: text("section"),
    /** The customer's own question id (e.g. "AC-03"), when the sheet has one. */
    externalId: text("external_id"),
    text: text("text").notNull(),
    /** Model draft, as generated (after guardrails). */
    draft: text("draft"),
    /** Reviewer's final answer (edited or accepted draft); what gets exported. */
    final: text("final"),
    status: questionStatusEnum("status").notNull().default("pending"),
    /** 0..1 */
    confidence: real("confidence"),
    citations: jsonb("citations").$type<CitationRef[]>().notNull().default([]),
    /** What retrieval returned (ids and scores), for audit and the citation panel. */
    retrieval: jsonb("retrieval").$type<Record<string, unknown>>(),
    /** Model note (e.g. which document would answer it) or the reviewer's task text. */
    notes: text("notes"),
    reviewedBy: text("reviewed_by").references(() => user.id, { onDelete: "set null" }),
    reviewedAt: timestamp("reviewed_at", { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("questions_questionnaire_row_idx").on(t.questionnaireId, t.rowNumber),
    index("questions_questionnaire_status_idx").on(t.questionnaireId, t.status),
    index("questions_org_status_idx").on(t.orgId, t.status),
  ],
);

