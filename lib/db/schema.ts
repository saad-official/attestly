/**
 * Database schema (spec section 4). Everything, including Better Auth's
 * tables, lives in the `attestly` Postgres schema so the database can be
 * dedicated or shared with other apps. The pgvector extension itself is
 * created by the first migration (in the database's default schema, usually
 * `public`), so `vector(768)` and the `<=>` operator resolve via search_path.
 *
 * Multi-tenancy is by `org_id` plus explicit `where` clauses in
 * `lib/db/repositories/*` (no row-level security). Every tenant table carries
 * `org_id`, even when it is derivable through a parent, so each query can
 * filter on it directly.
 *
 * Hand-written migrations (drizzle/):
 * - 0001_vector_indexes: chunks.tsv (generated tsvector), HNSW cosine indexes
 *   on both embedding columns, GIN on chunks.tsv.
 * - 0002_agent_events_append_only: trigger that rejects UPDATE, DELETE and
 *   TRUNCATE on agent_events.
 */
import { sql, type SQL } from "drizzle-orm";
import {
  boolean,
  customType,
  index,
  integer,
  jsonb,
  pgSchema,
  primaryKey,
  real,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  vector,
} from "drizzle-orm/pg-core";

export const attestly = pgSchema("attestly");

/** Gemini embeddings requested with `outputDimensionality: 768` (spec 4). */
export const EMBEDDING_DIMENSIONS = 768;

const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () =>
  timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

