export const chunks = attestly.table(
  "chunks",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    documentId: uuid("document_id")
      .notNull()
      .references(() => documents.id, { onDelete: "cascade" }),
    orgId: uuid("org_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    /** Order within the document, from 0. */
    position: integer("position").notNull(),
    /** Heading trail, e.g. ["Access Control", "2. Passwords"]. */
    headingPath: text("heading_path").array().notNull().default(sql`'{}'::text[]`),
    text: text("text").notNull(),
    tokenCount: integer("token_count").notNull().default(0),
    /** null until embedded (the daily cron retries failed embeddings). */
    embedding: vector("embedding", { dimensions: EMBEDDING_DIMENSIONS }),
    /** Generated by Postgres from heading_path and text; never written by the app. */
    tsv: tsvector("tsv").generatedAlwaysAs(
      (): SQL =>
        sql`setweight(to_tsvector('english'::regconfig, coalesce(attestly.immutable_join(heading_path), '')), 'A') || setweight(to_tsvector('english'::regconfig, coalesce("text", '')), 'B')`,
    ),
    createdAt: createdAt(),
  },
  (t) => [
    index("chunks_document_position_idx").on(t.documentId, t.position),
    index("chunks_org_idx").on(t.orgId),
    index("chunks_embedding_hnsw_idx").using("hnsw", t.embedding.op("vector_cosine_ops")),
    index("chunks_tsv_gin_idx").using("gin", t.tsv),
  ],
);

export type CitationRef = {
  /** Exactly one of chunkId / libraryAnswerId is set. */
  chunkId?: string;
  libraryAnswerId?: string;
  /** Verbatim passage from the cited text (validated by lib/draft guardrails). */
  quote: string;
};

export const libraryAnswers = attestly.table(
  "library_answers",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    orgId: uuid("org_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    question: text("question").notNull(),
    answer: text("answer").notNull(),
    source: librarySourceEnum("source").notNull().default("manual"),
    questionnaireId: uuid("questionnaire_id").references(() => questionnaires.id, { onDelete: "set null" }),
    /** The approved question this answer came from; unique so re-approving updates in place. */
    questionId: uuid("question_id").references(() => questions.id, { onDelete: "set null" }),
    /** Embedding of the question text; null until embedded. */
    embedding: vector("embedding", { dimensions: EMBEDDING_DIMENSIONS }),
    approvedAt: timestamp("approved_at", { withTimezone: true }).notNull().defaultNow(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("library_answers_org_created_idx").on(t.orgId, t.createdAt.desc()),
    uniqueIndex("library_answers_question_key").on(t.questionId).where(sql`${t.questionId} is not null`),
    index("library_answers_embedding_hnsw_idx").using("hnsw", t.embedding.op("vector_cosine_ops")),
  ],
);

